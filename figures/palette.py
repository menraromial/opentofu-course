"""Generate the figure colours from palette.tsv.

One source for three uses:
  - lib/tofu-colors.tex: \\definecolor for TikZ (light theme values);
  - ../src/css/figures.css: CSS variables for both themes;
  - the hex -> variable table used by svgpost.py.

svgpost.py matches a colour within 2 units per channel, so two palette
colours must differ by at least 6 on one channel, otherwise this script
stops.
"""
from itertools import combinations
from pathlib import Path

HERE = Path(__file__).parent


def read_palette():
    rows = []
    for line in (HERE / "palette.tsv").read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        name, light, var, dark = line.split("\t")
        rows.append((name, light.upper(), var, dark.upper()))
    return rows


def distance(a, b):
    return max(abs(int(a[i:i + 2], 16) - int(b[i:i + 2], 16)) for i in (0, 2, 4))


def check(pal):
    # TikZ white and black are converted separately by svgpost.py
    hues = [(n, c) for n, c, _, _ in pal] + [("white", "FFFFFF"), ("black", "000000")]
    close = [(a, b) for (a, ca), (b, cb) in combinations(hues, 2) if distance(ca, cb) < 6]
    if close:
        raise SystemExit(f"colours too close in palette.tsv: {close}")


def main():
    pal = read_palette()
    check(pal)
    tex = ["% Generated by palette.py: do not edit by hand."]
    tex += [f"\\definecolor{{{n}}}{{HTML}}{{{c}}}" for n, c, _, _ in pal]
    (HERE / "lib" / "tofu-colors.tex").write_text("\n".join(tex) + "\n")

    css = ["/* Generated by figures/palette.py: do not edit by hand. */", ":root {"]
    css += [f"  {v}: #{c};" for _, c, v, _ in pal]
    css += ["}", "[data-theme='dark'] {"]
    css += [f"  {v}: #{s};" for _, _, v, s in pal]
    css += ["}"]
    (HERE.parent / "src" / "css" / "figures.css").write_text("\n".join(css) + "\n")


if __name__ == "__main__":
    main()
